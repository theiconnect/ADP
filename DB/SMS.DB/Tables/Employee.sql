CREATE TABLE [dbo].[Employee]
(
	EmployeeIdPk INT NOT NULL PRIMARY KEY,
	FirstName VARCHAR(256) NOT NULL,
	MiddleName VARCHAR(256) NOT NULL,
	LastName VARCHAR(256) NOT NULL,
	Gender VARCHAR(50) NULL,
	DateOfBirth DATETIME NULL,
	HighestQualification VARCHAR(256) NULL,
	AadharCard VARCHAR(128) NULL,
	PanCard VARCHAR(128) NULL,
	BloodGroup VARCHAR(50) NULL,
	Department VARCHAR(256) NULL,
	Designation VARCHAR(128) NULL,
	CurrentAddressLine1 VARCHAR(256) NULL,
	CurrentAddressLine2 VARCHAR(256) NULL,
	CurrentCity VARCHAR(128) NULL,
	CurrentState VARCHAR(128) NULL,
	CurrentZip VARCHAR(20) NULL,
	PermanentAddressLine1 VARCHAR(256) NULL,
	PermanentAddressLine2 VARCHAR(256) NULL,
	PermanentCity VARCHAR(128) NULL,
	PermanentState VARCHAR(128)NULL,
	PermanentZip VARCHAR(20)NULL,
	Mobile VARCHAR(20) NOT NULL,
	AlternatePhone VARCHAR(20) NOT NULL,
	PersonalEmail VARCHAR(128) NULL,
	Email VARCHAR(128) NULL,
	EmergencyContactName VARCHAR(256) NULL,
	EmergencyContactPhone VARCHAR(20) NULL,
	DateofJoining DATETIME NULL,
	CurrentStore VARCHAR(256) NOT NULL,
	CurrentWH VARCHAR(256) NOT NULL,
	CurrentSalary VARCHAR(128) NULL,
	BankName VARCHAR(256) NOT NULL,
	ACNo VARCHAR(128) NOT NULL,
	IFSC VARCHAR(20) NOT NULL,
	AccountType VARCHAR(20) NOT NULL,
	Branch VARCHAR(256) NOT NULL,
	CreatedBy VARCHAR(512) NOT NULL,
	CreatedOn DATETIME NOT NULL DEFAULT(GETDATE()),
	LastUpdatedBy VARCHAR(512) NULL,
	LastUpdatedOn DATETIME NULL


)
